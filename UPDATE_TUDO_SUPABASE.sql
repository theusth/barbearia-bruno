-- 5) LOG AO PROPRIETÁRIO ALTERAR STATUS
create or replace function public.owner_set_appointment_status(
  p_appointment_id uuid,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old_status text;
  v_date date;
  v_time time;
begin
  if not public.is_owner() then
    raise exception 'Acesso negado.';
  end if;

  if p_status not in ('confirmed','completed','cancelled','no_show') then
    raise exception 'Status inválido.';
  end if;

  select status, appointment_date, appointment_time
    into v_old_status, v_date, v_time
  from public.appointments
  where id = p_appointment_id;

  if not found then
    raise exception 'Agendamento não encontrado.';
  end if;

  update public.appointments
     set status = p_status
   where id = p_appointment_id;

  perform public.write_activity_log(
    auth.uid(),
    'appointment_status_changed',
    'appointment',
    p_appointment_id::text,
    'Status do agendamento alterado de ' || v_old_status ||
      ' para ' || p_status || ' • ' ||
      to_char(v_date, 'DD/MM/YYYY') || ' ' ||
      to_char(v_time, 'HH24:MI'),
    jsonb_build_object(
      'old_status', v_old_status,
      'new_status', p_status
    )
  );
end;
$$;

revoke all on function public.owner_set_appointment_status(uuid,text) from public;
grant execute on function public.owner_set_appointment_status(uuid,text) to authenticated;

-- 6) LOG DE ALTERAÇÃO DE SERVIÇOS
create or replace function public.log_service_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    perform public.write_activity_log(
      auth.uid(),
      'service_created',
      'service',
      new.id::text,
      'Serviço criado: ' || new.name || ' • R$ ' || new.price::text,
      jsonb_build_object('name',new.name,'price',new.price,'duration',new.duration_minutes)
    );
    return new;
  elsif tg_op = 'UPDATE' then
    perform public.write_activity_log(
      auth.uid(),
      'service_updated',
      'service',
      new.id::text,
      'Serviço alterado: ' || new.name ||
        ' • preço R$ ' || old.price::text || ' → R$ ' || new.price::text,
      jsonb_build_object(
        'old_price',old.price,
        'new_price',new.price,
        'old_active',old.active,
        'new_active',new.active
      )
    );
    return new;
  elsif tg_op = 'DELETE' then
    perform public.write_activity_log(
      auth.uid(),
      'service_deleted',
      'service',
      old.id::text,
      'Serviço removido: ' || old.name,
      jsonb_build_object('name',old.name)
    );
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists trg_log_service_change on public.services;
create trigger trg_log_service_change
after insert or update or delete on public.services
for each row execute function public.log_service_change();

