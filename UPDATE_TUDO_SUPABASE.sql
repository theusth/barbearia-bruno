create or replace function public.owner_dashboard_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  result jsonb;
begin
  if not public.is_owner() then
    raise exception 'Acesso negado.';
  end if;

  select jsonb_build_object(
    'appointments_today',
      (select count(*) from public.appointments
       where appointment_date = current_date and status <> 'cancelled'),
    'future_appointments',
      (select count(*) from public.appointments
       where appointment_date >= current_date and status = 'confirmed'),
    'total_clients',
      (select count(*) from public.profiles where role = 'client'),
    'completed_revenue',
      coalesce((select sum(s.price)
       from public.appointments a
       join public.services s on s.id = a.service_id
       where a.status = 'completed'),0)
  ) into result;

  return result;
end;
$$;

