        p_notes,
        auth.uid(),
        v_group_id,
        p_duration_days,
        p_weekday,
        p_frequency_weeks
      );

      v_created := v_created + 1;
    end if;
  end loop;

  if v_created = 0 then
    raise exception 'Nenhum horário pôde ser bloqueado. Os horários da série já estão ocupados.';
  end if;

  return jsonb_build_object(
    'group_id', v_group_id,
    'created', v_created,
    'skipped', v_skipped,
    'frequency_weeks', p_frequency_weeks,
    'start_date', p_start_date,
    'end_date', v_end_date
  );
end;
