-- Função interna para gravar log.
create or replace function public.write_activity_log(
  p_actor_id uuid,
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_description text,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_role text;
begin
  if p_actor_id is not null then
    select name, role into v_name, v_role
    from public.profiles
    where id = p_actor_id;
  end if;

  insert into public.activity_logs (
    actor_id, actor_name, actor_role, action,
    entity_type, entity_id, description, metadata
  )
  values (
    p_actor_id, v_name, v_role, p_action,
    p_entity_type, p_entity_id, p_description, coalesce(p_metadata, '{}'::jsonb)
  );
end;
$$;

revoke all on function public.write_activity_log(uuid,text,text,text,text,jsonb) from public, anon, authenticated;

