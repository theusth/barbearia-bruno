-- 4) LOG AO CANCELAR PELO CLIENTE
create or replace function public.cancel_my_appointment(p_appointment_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_date date;
  v_time time;
begin
  update public.appointments
     set status = 'cancelled'
   where id = p_appointment_id
     and client_id = auth.uid()
     and status = 'confirmed'
  returning appointment_date, appointment_time into v_date, v_time;

  if not found then
    raise exception 'Agendamento não encontrado ou não pode ser cancelado.';
  end if;

  perform public.write_activity_log(
    auth.uid(),
    'appointment_cancelled',
    'appointment',
    p_appointment_id::text,
    'Cliente cancelou o agendamento de ' ||
      to_char(v_date, 'DD/MM/YYYY') || ' às ' ||
      to_char(v_time, 'HH24:MI'),
    jsonb_build_object('status', 'cancelled')
  );
end;
$$;

revoke all on function public.cancel_my_appointment(uuid) from public;
